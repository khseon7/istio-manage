#!/bin/bash

CLUSTER_NAME="istio-lab"
REGION="ap-northeast-2"

echo "----------------------------------------------------"
echo "작업 시작: EKS 클러스터 및 관련 리소스 삭제를 시작합니다."
echo "클러스터 이름: $CLUSTER_NAME"
echo "리전: $REGION"
echo "----------------------------------------------------"

# 1. 클러스터 삭제 실행
eksctl delete cluster --name $CLUSTER_NAME --region $REGION

# 2. 결과 확인
if [ $? -eq 0 ]; then
    echo "----------------------------------------------------"
    echo "성공: 클러스터가 안전하게 철거되었습니다."
    echo "이제 AWS 콘솔에서 EC2(사령부)를 '중지(Stop)' 하셔도 됩니다."
    echo "----------------------------------------------------"
else
    echo "----------------------------------------------------"
    echo "오류: 삭제 중 문제가 발생했습니다. AWS 콘솔을 확인해 주세요."
    echo "----------------------------------------------------"
fi
